import type { PluginListenerHandle } from '@capacitor/core';

/**
 * What went wrong with a connection. A closed set: the native side never sends another word.
 *
 * - `pin-mismatch`: the server's public key is not the one the QR code named.
 * - `host-mismatch`: the key is right, but the certificate does not name the host dialled.
 * - `unreachable`: nothing answered at that address, or no WebSocket service did.
 * - `tls`: the handshake failed for another reason (TLS 1.2 only, a bad signature).
 * - `closed`: the connection ended without a close frame, or a write failed.
 */
export type TransportErrorKind = 'pin-mismatch' | 'host-mismatch' | 'unreachable' | 'tls' | 'closed';

export interface ConnectOptions {
  /**
   * The caller's name for the connection, echoed on every event. Chosen by the caller so it can
   * listen before the call returns: a refused handshake can end the connection before then.
   * Generated by the plugin when absent.
   */
  id?: string;
  /** `wss://host:port/path`. Only `wss` is accepted: the plugin does TLS itself. */
  url: string;
  /** base64url (no padding) of SHA-256 of the certificate's SubjectPublicKeyInfo. */
  pin: string;
}

export interface OpenEvent {
  id: string;
}
export interface MessageEvent {
  id: string;
  text: string;
}
export interface CloseEvent {
  id: string;
  code: number;
  reason: string;
}
export interface ErrorEvent {
  id: string;
  kind: TransportErrorKind;
  message: string;
}

export interface RuntimeInfo {
  /** Connection tasks running in the shared Rust runtime. */
  live: number;
  /** Worker threads of that runtime. Fixed: it does not grow with connections. */
  workers: number;
}

/**
 * The pinned connection to the desktop.
 *
 * Every connection ends with exactly one `close` event. A failure sends `error` first, then
 * `close` with code 1006 and the error's kind as the reason.
 */
export interface CoasysTransportPlugin {
  /** Starts a connection and returns its id at once. `open` or the ending follows as events. */
  connect(options: ConnectOptions): Promise<{ id: string }>;
  /** Sends one text frame. Rejects when the connection has ended. */
  send(options: { id: string; text: string }): Promise<void>;
  /** Closes with code 1000. `close` follows as an event. */
  close(options: { id: string }): Promise<void>;
  /**
   * One HTTP request to the paired desktop over the same pinned TLS: for the few executor calls
   * that are HTTP rather than socket (ad4m-connect's `/health`). `https://` only; text bodies only.
   * Rejects with the error kind as its `code` when there is no response.
   */
  request(options: {
    url: string;
    pin: string;
    method?: string;
    headers?: Record<string, string>;
    body?: string;
  }): Promise<{ status: number; headers: Record<string, string>; body: string }>;
  /**
   * Closes every connection the plugin holds. A page calls it once, before its first connection,
   * to close what a previous page in this WebView left open (`PinnedWebSocket` does this itself).
   */
  reset(): Promise<{ closed: number }>;
  /** The shared runtime's state, for the leak check. */
  runtimeInfo(): Promise<RuntimeInfo>;

  addListener(event: 'open', listener: (e: OpenEvent) => void): Promise<PluginListenerHandle>;
  addListener(event: 'message', listener: (e: MessageEvent) => void): Promise<PluginListenerHandle>;
  addListener(event: 'close', listener: (e: CloseEvent) => void): Promise<PluginListenerHandle>;
  addListener(event: 'error', listener: (e: ErrorEvent) => void): Promise<PluginListenerHandle>;
  removeAllListeners(): Promise<void>;
}
